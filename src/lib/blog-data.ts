/** Get all blog posts */
export function getAllPosts(): BlogPost[] {
  return blogPosts;
}

/** Get a single blog post by its slug */
export function getPostBySlug(slug: string): BlogPost | undefined {
  return blogPosts.find((post) => post.slug === slug);
}

/** Get the N most recent blog posts */
export function getRecentPosts(n: number = 3): BlogPost[] {
  return [...blogPosts]
    .sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime())
    .slice(0, n);
}

/** Get all unique categories */
export function getAllCategories(): { name: string; slug: string }[] {
  const seen = new Set<string>();
  return blogPosts
    .filter((post) => {
      if (seen.has(post.categorySlug)) return false;
      seen.add(post.categorySlug);
      return true;
    })
    .map((post) => ({ name: post.category, slug: post.categorySlug }));
}

/** Get related posts (same category, excluding current) */
export function getRelatedPosts(slug: string, n: number = 3): BlogPost[] {
  const current = getPostBySlug(slug);
  if (!current) return [];
  return blogPosts
    .filter(
      (post) =>
        post.slug !== slug &&
        post.categorySlug === current.categorySlug
    )
    .slice(0, n)
    .concat(
      blogPosts
        .filter(
          (post) =>
            post.slug !== slug &&
            post.categorySlug !== current.categorySlug
        )
        .slice(0, Math.max(0, n - blogPosts.filter((post) => post.slug !== slug && post.categorySlug === current.categorySlug).length))
    )
    .slice(0, n);
}
